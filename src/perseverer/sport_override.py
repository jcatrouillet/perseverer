def set_fueling_override(
    conn: Connection,
    *,
    athlete_id: str,
    activity_id: str,
    carbohydrates_g: float | None,
    sodium_mg: float | None,
) -> None:
    """Records the athlete's own carbohydrate/sodium intake for this activity -- same shape as
    `set_sport_override`/`set_race_override`/`set_name_override`, upserting on the
    athlete/start_time_utc identity without touching any separate correction already recorded on
    that same row, and applying immediately. Unlike the other three, there's nothing to
    "correct" here (see module docstring) -- this is the athlete's only source for this data."""
    start_time_utc = _start_time_for(conn, athlete_id=athlete_id, activity_id=activity_id)

    now = datetime.now(UTC).replace(tzinfo=None)
    stmt = sqlite_insert(activity_sport_override).values(
        athlete_id=athlete_id,
        start_time_utc=start_time_utc,
        carbohydrates_g=carbohydrates_g,
        sodium_mg=sodium_mg,
        created_at=now,
    )
    conn.execute(
        stmt.on_conflict_do_update(
            index_elements=["athlete_id", "start_time_utc"],
            set_={
                "carbohydrates_g": carbohydrates_g,
                "sodium_mg": sodium_mg,
                "created_at": now,
            },
        )
    )
    conn.execute(
        activity.update()
        .where(activity.c.id == activity_id)
        .values(carbohydrates_g=carbohydrates_g, sodium_mg=sodium_mg, updated_at=now)
    )


def apply_sport_overrides(conn: Connection, *, athlete_id: str) -> int:
    """Re-applies every recorded correction (sport, race, name, and/or fueling) -- called at the
    end of `sync rebuild` so a manual correction survives a full wipe-and-replay. Matches by exact
    `start_time_utc` equality (not a tolerance window like the Garmin-summary correction's
    cross-source timestamp matching): both sides come from the same archived bytes, so they're
    identical down to the second, not just close. Only the columns actually recorded on a given
    override row are written -- a race-only correction never overwrites `sport`/`sub_sport` back
    to null, and vice versa. Returns the number of activities corrected."""
    overrides = conn.execute(
        select(
            activity_sport_override.c.start_time_utc,
            activity_sport_override.c.sport,
            activity_sport_override.c.sub_sport,
            activity_sport_override.c.is_race,
            activity_sport_override.c.name,
            activity_sport_override.c.carbohydrates_g,
            activity_sport_override.c.sodium_mg,
        ).where(activity_sport_override.c.athlete_id == athlete_id)
    ).fetchall()
    if not overrides:
        return 0

    now = datetime.now(UTC).replace(tzinfo=None)
    corrected = 0
    for o in overrides:
        values: dict[str, object] = {"updated_at": now}
        if o.sport is not None:
            values["sport"] = o.sport
            values["sub_sport"] = o.sub_sport
        if o.is_race is not None:
            values["is_race"] = o.is_race
        if o.name is not None:
            values["name"] = o.name
        if o.carbohydrates_g is not None:
            values["carbohydrates_g"] = o.carbohydrates_g
        if o.sodium_mg is not None:
            values["sodium_mg"] = o.sodium_mg
        result = conn.execute(
            activity.update()
            .where(
                activity.c.athlete_id == athlete_id,
                activity.c.start_time_utc == o.start_time_utc,
                activity.c.deleted_at.is_(None),
            )
            .values(**values)
        )
        corrected += result.rowcount
    return corrected
